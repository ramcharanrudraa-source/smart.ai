export function getInitialBins(): GarbageBin[] {
  return RAW_BINS.map((raw) => {
    const priority = calculateBinPriority(raw, DEFAULT_ALGORITHM_WEIGHTS);
    return {
      ...raw,
      priorityScore: priority.priorityScore,
      priorityLevel: priority.priorityLevel,
      scoreBreakdown: priority.scoreBreakdown,
      assignedTruckId: null,
    };
  });
}

